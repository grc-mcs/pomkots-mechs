package grcmcs.minecraft.mods.pomkotsmechs.forge.mixin;

import net.minecraftforge.fml.loading.LoadingModList;
import org.objectweb.asm.tree.ClassNode;
import org.spongepowered.asm.mixin.extensibility.IMixinConfigPlugin;
import org.spongepowered.asm.mixin.extensibility.IMixinInfo;

import java.util.List;
import java.util.Set;

/**
 * Prevents compatibility mixins from being loaded when their optional mod is absent.
 */
public final class PomkotsForgeMixinPlugin implements IMixinConfigPlugin {
    private static final String CREATE_WORLD_SCREEN_MIXIN =
            "grcmcs.minecraft.mods.pomkotsmechs.forge.mixin.CreateWorldScreenMixin";

    @Override
    public void onLoad(String mixinPackage) {
    }

    @Override
    public String getRefMapperConfig() {
        return null;
    }

    @Override
    public boolean shouldApplyMixin(String targetClassName, String mixinClassName) {
        if (CREATE_WORLD_SCREEN_MIXIN.equals(mixinClassName)) {
            return LoadingModList.get().getModFileById("lostcities") != null;
        }
        return true;
    }

    @Override
    public void acceptTargets(Set<String> myTargets, Set<String> otherTargets) {
    }

    @Override
    public List<String> getMixins() {
        return null;
    }

    @Override
    public void preApply(String targetClassName, ClassNode targetClass,
                         String mixinClassName, IMixinInfo mixinInfo) {
    }

    @Override
    public void postApply(String targetClassName, ClassNode targetClass,
                          String mixinClassName, IMixinInfo mixinInfo) {
    }
}
